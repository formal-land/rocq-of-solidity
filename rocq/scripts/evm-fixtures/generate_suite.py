"""Regenerate a pinned Ethereum fixture suite and verify its fork snapshot."""
import hashlib
import json
import sys
from dataclasses import replace
from pathlib import Path
from string import Template

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import evm_tests_generate as gen

HERE = Path(__file__).resolve().parent
SUITES = json.loads((HERE / "suites.json").read_text())


def selected_cases(root, ranges, include_nested_budget):
    # The release fixes the JSON insertion order. Paths use the generator's
    # sorted traversal. Each interval includes both endpoints.
    selected = {i for start, end in ranges for i in range(start, end + 1)}
    index = 0
    for path in gen.fixture_json_files(root):
        file = gen.fixture_relative_path(root, path)
        for name, fixture in gen.read_json(path).items():
            for fork, posts in fixture["post"].items():
                for post in range(len(posts)):
                    if index in selected:
                        entry = dict(id=gen.discovered_identifier(file, name, fork, post),
                                     file=file, test=name, fork=fork, post_index=post)
                        yield gen.build_case_from_fixture(
                            1000, entry, fixture, pinned_case=True,
                            include_nested_budget=include_nested_budget,
                        )
                    index += 1


def osaka_cases(root):
    directory = root / "fixtures/state_tests/for_osaka/osaka"
    for path in sorted(directory.rglob("*.json")):
        file = gen.fixture_relative_path(root, path)
        for test, fixture in gen.read_json(path).items():
            for post in range(len(fixture["post"]["Osaka"])):
                entry = dict(id=gen.discovered_identifier(file, test, "Osaka", post),
                             file=file, test=test, fork="Osaka", post_index=post)
                yield gen.build_case_from_fixture(1000, entry, fixture, cap_step_hint=True)


def generate(root, out, name, smoke=False, archive=False):
    suite = SUITES[name]
    if smoke:
        allowlist = gen.read_json(gen.DEFAULT_ALLOWLIST)
        cases = (gen.build_case(root, allowlist["default_steps"], e) for e in allowlist["cases"])
    elif name == "GeneratedOsaka":
        cases = osaka_cases(root)
    else:
        cases = selected_cases(root, suite["ranges"], name == "GeneratedStStaticProbeNew")
    template_path = HERE / (name + ".v.in")
    template = Template(template_path.read_text()) if template_path.exists() else None
    hashes = {}
    imports = []
    out.mkdir(parents=True, exist_ok=True)
    for case in cases:
        filename = case.case_id + ".v"
        if filename in hashes:
            raise ValueError(f"duplicate fixture {filename}")
        use_vm = name == "GeneratedOsaka"
        if not archive:
            runtime_error = suite.get("execution_errors", {}).get(case.case_id)
            if runtime_error is not None:
                case = replace(case, expected_error=runtime_error)
            if name == "GeneratedStStaticProbeNew" and case.file.endswith("/static_LoopCallsThenRevert.json"):
                use_vm = True
        content = gen.generate_case(
            case, template, name == "GeneratedStPre2Probe", use_vm=use_vm
        ).encode()
        path = out / filename
        if not path.exists() or path.read_bytes() != content:
            path.write_bytes(content)
        hashes[filename] = hashlib.sha256(content).digest()
        imports.append(f"Require Import RocqOfSolidity.Evm.Tests.Ethereum.{name}.{case.case_id}.")
    digest = hashlib.sha256()
    for filename in sorted(hashes):
        digest.update(filename.encode() + b"\0" + hashes[filename])
    actual = digest.hexdigest()
    print(f"{name}: {len(hashes)} cases, SHA-256 {actual}", flush=True)
    expected = suite["archive_sha256" if archive else "sha256"]
    if not smoke and actual != expected:
        raise ValueError(f"expected suite digest {expected}")
    manifest = "(* Generated by rocq/scripts/evm_tests_generate.py. *)\n" + "\n".join(imports) + "\n"
    (out / "Manifest.v").write_text(manifest)
    return list(hashes)
